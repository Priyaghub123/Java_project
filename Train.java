public class Train {
    int trainNo;
    String name;
    String from;
    String to;
    String time;
    int seats;

    public Train(int trainNo, String name, String from, String to, String time, int seats) {
        this.trainNo = trainNo;
        this.name = name;
        this.from = from;
        this.to = to;
        this.time = time;
        this.seats = seats;
    }
}